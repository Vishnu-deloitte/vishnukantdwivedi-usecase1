"""
agents/reporter.py
Reporter agent — answers the business question by querying Gold tables
with SQL (DuckDB) and produces a self-contained HTML executive report
with embedded Plotly charts, plus a structured JSON analysis.
"""
import json
import re
from pathlib import Path
from typing import List

import duckdb
import pandas as pd
import plotly.express as px
import plotly.io as pio
from langchain_core.tools import tool
from langchain_core.messages import HumanMessage, SystemMessage, ToolMessage

from core.config import REPORTS_DIR, make_llm
from core.observability import AgentTrace

SYSTEM_PROMPT = """You are the Reporter agent. Your goal is to answer the business question
using the Gold tables. You have a strict 7-step budget — be efficient.

Follow these steps IN ORDER, one tool call per step:
1. Call inspect_gold_tables_tool to preview schemas and sample rows.
2. Call load_gold_data_tool to register the Gold Parquet files as DuckDB tables.
3. Call execute_query_tool with ONE SQL SELECT query that fetches the data needed.
4. Immediately reply with ONLY a valid JSON object (no markdown fences, no extra text):
   {"direct_answer": "1-2 sentence answer", "detailed_analysis": "short paragraph",
    "charts": [{"title": str, "chart_type": "bar"|"line"|"pie"|"scatter", "x": col, "y": col, "sql": str}]}

Do NOT call more than one SQL query. Do NOT add any text before or after the JSON.
"""


def _table_name_from_path(p: str) -> str:
    return re.sub(r"[^0-9a-zA-Z_]", "_", Path(p).stem)


def _parse_llm_json(text: str) -> dict:
    text = text.strip()
    start, end = text.find("{"), text.rfind("}")
    if start != -1 and end != -1:
        try:
            return json.loads(text[start : end + 1])
        except json.JSONDecodeError:
            pass
    return {}


def _render_chart_html(con: duckdb.DuckDBPyConnection, chart_spec: dict) -> str:
    try:
        df = con.execute(chart_spec["sql"]).df()
    except Exception as e:  # noqa: BLE001
        return f"<p><em>Could not render chart '{chart_spec.get('title')}': {e}</em></p>"

    chart_type = chart_spec.get("chart_type", "bar")
    x, y = chart_spec.get("x"), chart_spec.get("y")
    title = chart_spec.get("title", "")
    try:
        if chart_type == "line":
            fig = px.line(df, x=x, y=y, title=title)
        elif chart_type == "pie":
            fig = px.pie(df, names=x, values=y, title=title)
        elif chart_type == "scatter":
            fig = px.scatter(df, x=x, y=y, title=title)
        else:
            fig = px.bar(df, x=x, y=y, title=title)
    except Exception as e:  # noqa: BLE001
        return f"<p><em>Could not plot chart '{title}': {e}</em></p>"

    return pio.to_html(fig, full_html=False, include_plotlyjs="cdn")


def _build_html_report(analysis: dict, chart_html_blocks: List[str], business_intent: str, run_id: str) -> str:
    charts_html = "\n".join(f"<div class='chart'>{c}</div>" for c in chart_html_blocks)
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Executive Report — {run_id[:8]}</title>
<style>
  body {{ font-family: -apple-system, Segoe UI, Roboto, sans-serif; margin: 40px auto; max-width: 900px; color: #1a1a1a; }}
  h1 {{ font-size: 1.6em; }}
  .question {{ color: #555; font-style: italic; margin-bottom: 24px; }}
  .answer {{ background: #f4f6fb; border-left: 4px solid #4a6fdc; padding: 16px 20px; margin-bottom: 24px; }}
  .chart {{ margin: 24px 0; }}
  footer {{ margin-top: 40px; color: #888; font-size: 0.85em; }}
</style>
</head>
<body>
  <h1>Executive Report</h1>
  <p class="question">Business question: {business_intent}</p>
  <div class="answer">
    <strong>Direct answer:</strong> {analysis.get('direct_answer', 'N/A')}
  </div>
  <p>{analysis.get('detailed_analysis', '')}</p>
  {charts_html}
  <footer>Generated by the Reporter agent · run_id {run_id}</footer>
</body>
</html>"""


def generate_report(gold_files: List[str], business_intent: str, run_id: str, task_description: str = "") -> str:
    """Runs the Reporter agent. Returns the path to the written HTML report."""
    trace = AgentTrace("reporter", run_id, input_data={"gold_files": gold_files, "business_intent": business_intent})
    con = duckdb.connect(database=":memory:")
    scratchpad: dict = {"table_names": {}}

    @tool
    def inspect_gold_tables_tool(confirmation: str = "inspect") -> str:
        """Preview Gold table schemas and 3 sample rows (no DuckDB registration yet)."""
        trace.log_tool_call("inspect_gold_tables_tool")
        preview = {}
        for p in gold_files:
            df = pd.read_parquet(p)
            preview[_table_name_from_path(p)] = {
                "columns": list(df.columns),
                "sample_rows": df.head(3).to_dict(orient="records"),
            }
        content = json.dumps(preview, default=str)
        trace.log_tool_result("inspect_gold_tables_tool", content[:2000])
        return content

    @tool
    def load_gold_data_tool(confirmation: str = "load") -> str:
        """Register all Gold Parquet files as DuckDB in-memory tables."""
        trace.log_tool_call("load_gold_data_tool")
        names = []
        for p in gold_files:
            tname = _table_name_from_path(p)
            con.execute(f"CREATE OR REPLACE TABLE {tname} AS SELECT * FROM read_parquet('{p}')")
            scratchpad["table_names"][tname] = p
            names.append(tname)
        content = json.dumps({"tables_loaded": names})
        trace.log_tool_result("load_gold_data_tool", content)
        return content

    @tool
    def execute_query_tool(sql_query: str) -> str:
        """Run an agent-written SQL SELECT query against the loaded Gold tables, returns JSON rows."""
        trace.log_tool_call("execute_query_tool", {"sql_query": sql_query})
        try:
            result_df = con.execute(sql_query).df()
            content = result_df.to_json(orient="records")
        except Exception as e:  # noqa: BLE001
            content = json.dumps({"error": str(e)})
        trace.log_tool_result("execute_query_tool", content[:2000])
        return content

    tools = [inspect_gold_tables_tool, load_gold_data_tool, execute_query_tool]
    llm = make_llm().bind_tools(tools)
    tool_map = {t.name: t for t in tools}
    messages = [
        SystemMessage(content=SYSTEM_PROMPT),
        HumanMessage(content=f"Business question: {business_intent}\nTask: {task_description}\nGold files: {gold_files}\nBegin."),
    ]

    analysis: dict = {}
    for _ in range(7):  # 4 steps needed (inspect→load→query→answer) + 3 buffer
        ai_msg = llm.invoke(messages)
        messages.append(ai_msg)
        if ai_msg.content:
            trace.log_step("ai_reasoning", str(ai_msg.content))
            parsed = _parse_llm_json(str(ai_msg.content))
            if parsed:
                analysis = parsed
        if not getattr(ai_msg, "tool_calls", None):
            break
        for call in ai_msg.tool_calls:
            fn = tool_map[call["name"]]
            result = fn.invoke(call["args"])
            messages.append(ToolMessage(content=str(result), tool_call_id=call["id"]))

    if not analysis:
        # Fallback: ensure tables are loaded, produce a minimal analysis with no charts
        if not scratchpad["table_names"]:
            for p in gold_files:
                tname = _table_name_from_path(p)
                con.execute(f"CREATE OR REPLACE TABLE {tname} AS SELECT * FROM read_parquet('{p}')")
                scratchpad["table_names"][tname] = p
        analysis = {
            "direct_answer": "The agent could not produce a structured answer; see Gold tables for raw data.",
            "detailed_analysis": "",
            "charts": [],
        }

    chart_blocks = [_render_chart_html(con, c) for c in analysis.get("charts", [])]
    html = _build_html_report(analysis, chart_blocks, business_intent, run_id)

    html_path = REPORTS_DIR / f"report_{run_id[:8]}.html"
    json_path = REPORTS_DIR / f"report_{run_id[:8]}.json"
    html_path.write_text(html)
    json_path.write_text(json.dumps(analysis, indent=2, default=str))

    trace.finish(output={"report_html": str(html_path), "report_json": str(json_path)})
    return str(html_path)
